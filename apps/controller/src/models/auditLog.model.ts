/**
 * Compute a field-level diff for an update audit record.
 *
 * Only keys present in `after` are considered, so a partial patch does not report every
 * untouched field as "changed to undefined". Values are compared structurally.
 */
export function diffFields(
  before: Record<string, unknown>,
  after: Record<string, unknown>,
  options: { redact?: string[] } = {},
): { field: string; before?: unknown; after?: unknown }[] {
  const redact = new Set(options.redact ?? []);
  const changes: { field: string; before?: unknown; after?: unknown }[] = [];

  for (const [key, nextValue] of Object.entries(after)) {
    const previousValue = before[key];
    if (JSON.stringify(previousValue) === JSON.stringify(nextValue)) continue;

    changes.push(
      redact.has(key)
        ? { field: key, before: '[REDACTED]', after: '[REDACTED]' }
        : { field: key, before: previousValue, after: nextValue },
    );
  }

  return changes;
}

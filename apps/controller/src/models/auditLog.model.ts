import { z } from 'zod';
import { AuditAction, RecoveryStatus } from '@/constants/enums';
import { auditableShape, isoDateTime, mbpsSchema, scoreSchema } from './base.model';

/**
 * Audit log entry.
 *
 * DESIGN: ONE ENVELOPE, TYPED EXTENSIONS
 * =====================================
 * A single collection records every consequential action — a role change, a slice pause,
 * an arbitration decision. The alternative (a separate collection per event kind) makes the
 * most important question an auditor asks — *"show me everything that happened to the
 * cardiology slice between 14:00 and 15:00"* — into a fan-out across collections with
 * client-side merging.
 *
 * So: a common envelope (who, what, when, where, outcome) plus an optional typed extension
 * carrying the fields specific to an arbitration decision.
 *
 * IMMUTABILITY
 * ============
 * Audit entries are append-only. Nothing in the application updates or deletes them:
 * `AuditService` exposes no mutation, the Firestore security rules deny client writes
 * outright, and the retention sweep explicitly excludes this collection. An audit trail
 * that can be edited is not an audit trail.
 */

export const AuditOutcome = {
  SUCCESS: 'SUCCESS',
  FAILURE: 'FAILURE',
  DENIED: 'DENIED',
} as const;
export type AuditOutcome = (typeof AuditOutcome)[keyof typeof AuditOutcome];

/** Who performed the action. Denormalised on purpose — see the note below. */
export const AuditActorSchema = z.object({
  userId: z.string().min(1),
  email: z.string().max(254),
  role: z.string().max(32),
  displayName: z.string().max(120).optional(),
  ip: z.string().max(64).optional(),
  userAgent: z.string().max(512).optional(),
});

/** What the action was performed on. */
export const AuditTargetSchema = z.object({
  type: z.string().min(1).max(64),
  id: z.string().min(1).max(128),
  name: z.string().max(200).optional(),
  departmentId: z.string().max(128).optional(),
});

/**
 * Arbitration-specific detail.
 *
 * These are the fields the specification requires an arbitration audit record to carry.
 * They live in a typed sub-object rather than being flattened into the envelope, so a
 * `USER_LOGIN` record is not littered with twelve null bandwidth columns.
 */
export const ArbitrationAuditDetailSchema = z.object({
  decisionId: z.string().min(1),
  contentionId: z.string().min(1),
  /** Id + version of the policy in force, so the decision stays explainable after edits. */
  policyId: z.string().min(1),
  policyVersion: z.number().int().nonnegative(),
  policyName: z.string().max(200).optional(),

  /** Business priority score of the affected slice at decision time. */
  businessScore: scoreSchema,
  /** Human-readable justification generated by the arbitration engine. */
  reason: z.string().max(4000),
  /** 0–1; how strongly the engine preferred this plan over the runner-up. */
  confidence: z.number().min(0).max(1),

  bandwidthBeforeMbps: mbpsSchema,
  bandwidthAfterMbps: mbpsSchema,
  bandwidthReducedMbps: mbpsSchema,
  degradationPercent: z.number().min(0).max(100),
  durationSeconds: z.number().int().nonnegative(),
  expiresAt: isoDateTime.optional(),

  recoveryStatus: z.nativeEnum(RecoveryStatus).default(RecoveryStatus.NOT_APPLICABLE),
  recoveredAt: isoDateTime.optional(),

  /**
   * Counterfactual plans the engine evaluated and rejected, with the harm each would have
   * caused. This is what turns "the system degraded my slice" into a defensible answer.
   */
  alternatives: z
    .array(
      z.object({
        strategy: z.string().max(120),
        description: z.string().max(500),
        totalHarm: z.number().nonnegative(),
        rejectedBecause: z.string().max(500),
      }),
    )
    .max(10)
    .default([]),
});

export type ArbitrationAuditDetail = z.infer<typeof ArbitrationAuditDetailSchema>;

export const AuditLogSchema = z.object({
  ...auditableShape,

  action: z.nativeEnum(AuditAction),
  outcome: z.nativeEnum(AuditOutcome).default(AuditOutcome.SUCCESS),
  /** Epoch-ms mirror of `createdAt`, so range queries need no string parsing. */
  occurredAt: isoDateTime,
  occurredAtMs: z.number().int().nonnegative(),

  /**
   * Process-monotonic counter, used ONLY as a tiebreaker when two entries share a
   * millisecond.
   *
   * Without it, same-millisecond entries fall back to the identifier's random suffix and
   * an audit timeline renders in arbitrary order — so "contention resolved" can appear
   * above "contention detected". Under load, same-millisecond writes are routine rather
   * than exotic, and an audit trail that misreports the order of events is not an audit
   * trail.
   *
   * Not globally unique across instances; combined with `occurredAtMs` it is sufficient,
   * because two instances writing in the same millisecond have no true ordering anyway.
   */
  sequence: z.number().int().nonnegative().default(0),

  /**
   * The actor is COPIED, not referenced.
   *
   * An audit record must remain truthful even if the user is later renamed, has their role
   * changed, or is deleted entirely. A foreign key would make the trail retroactively
   * mutable — "who approved this?" must not have a different answer next year.
   */
  actor: AuditActorSchema,
  target: AuditTargetSchema.optional(),

  summary: z.string().min(1).max(500),
  /** Field-level before/after for CRUD actions. Redacted of secrets before storage. */
  changes: z
    .array(
      z.object({
        field: z.string().max(120),
        before: z.unknown().optional(),
        after: z.unknown().optional(),
      }),
    )
    .max(100)
    .optional(),

  /** Populated only for ARBITRATION_* and ALLOCATION_* actions. */
  arbitration: ArbitrationAuditDetailSchema.optional(),

  correlationId: z.string().max(128),
  /** Free-form context; must never contain credentials. */
  metadata: z.record(z.unknown()).optional(),
});

export type AuditLog = z.infer<typeof AuditLogSchema>;

